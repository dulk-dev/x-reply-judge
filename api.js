// TypeSafe Jev API layer. Everything that knows about the wire format lives here.
// Verified against https://docs.typesafe.ai/api/system-one.md (OpenAPI for POST /v1/systemone).
// Works both as a classic script (importScripts in the service worker) and as a CommonJS module (tests).

(function (root) {
  const DEFAULT_API_SETTINGS = Object.freeze({
    baseUrl: "https://api.typesafe.ai",
    path: "/v1/systemone",
    authHeader: "Authorization",
    authScheme: "Bearer",
    model: "jev-latest",
    questionKey: "ai_generated",
    // Dot path into the JSON response. "{q}" is replaced with questionKey.
    responsePath: "answers.{q}.noul",
    instructions:
      "Was this short social media reply most likely written or generated by an AI language model rather than by a human?"
  });

  // Request body: ONLY the reply text goes into `state`. No author, ids, timestamps or parent post.
  function buildRequestBody(text, cfg) {
    return {
      model: cfg.model,
      state: String(text),
      questions: {
        [cfg.questionKey]: { type: "noul", instructions: cfg.instructions }
      }
    };
  }

  function buildHeaders(apiKey, cfg) {
    const headers = { "Content-Type": "application/json" };
    if (cfg.authHeader) {
      headers[cfg.authHeader] = cfg.authScheme ? `${cfg.authScheme} ${apiKey}` : apiKey;
    }
    return headers;
  }

  function buildUrl(cfg) {
    const base = String(cfg.baseUrl || "").replace(/\/+$/, "");
    const path = String(cfg.path || "");
    return base + (path.startsWith("/") ? path : `/${path}`);
  }

  function getPath(obj, path) {
    return String(path)
      .split(".")
      .filter(Boolean)
      .reduce((value, key) => (value == null ? undefined : value[key]), obj);
  }

  // Returns an integer percentage 0-100 or throws. Accepts 0-1 probabilities;
  // values in (1, 100] are treated as already-percent for custom endpoints.
  function parseProbability(json, cfg) {
    const path = String(cfg.responsePath).split("{q}").join(cfg.questionKey);
    let value = getPath(json, path);
    if (typeof value === "string" && value.trim() !== "") value = Number(value);
    if (typeof value !== "number" || !Number.isFinite(value)) {
      throw new Error(`Response has no numeric value at "${path}"`);
    }
    if (value < 0 || value > 100) throw new Error(`Probability out of range: ${value}`);
    const pct = value <= 1 ? value * 100 : value;
    return Math.round(pct);
  }

  function describeHttpError(status, bodyText) {
    const known = {
      400: "Bad request (possibly too long for the model context)",
      401: "Missing or invalid API key",
      413: "Payload too large",
      415: "Unsupported media type",
      422: "Request failed validation",
      429: "Rate limit exceeded",
      529: "TypeSafe is temporarily overloaded"
    };
    const detail = (bodyText || "").slice(0, 200);
    return `HTTP ${status}: ${known[status] || "Request failed"}${detail ? ` - ${detail}` : ""}`;
  }

  const RETRYABLE = new Set([429, 529]);

  // Detect one reply text. Retries 429/529 with exponential backoff, honouring Retry-After.
  async function detectText(text, apiKey, cfg, options = {}) {
    const fetchFn = options.fetch || root.fetch.bind(root);
    const sleep = options.sleep || ((ms) => new Promise((r) => setTimeout(r, ms)));
    const maxRetries = options.maxRetries ?? 3;
    const timeoutMs = options.timeoutMs ?? 20000;

    for (let attempt = 0; ; attempt++) {
      const controller = typeof AbortController !== "undefined" ? new AbortController() : null;
      const timer = controller ? setTimeout(() => controller.abort(), timeoutMs) : null;
      let response;
      try {
        response = await fetchFn(buildUrl(cfg), {
          method: "POST",
          headers: buildHeaders(apiKey, cfg),
          body: JSON.stringify(buildRequestBody(text, cfg)),
          signal: controller?.signal
        });
      } catch (error) {
        throw new Error(error?.name === "AbortError" ? "Request timed out" : `Network error: ${error?.message || error}`);
      } finally {
        if (timer) clearTimeout(timer);
      }

      if (response.ok) {
        const json = await response.json();
        return { probability: parseProbability(json, cfg), model: json?.model || null };
      }

      if (RETRYABLE.has(response.status) && attempt < maxRetries) {
        const retryAfter = Number(response.headers?.get?.("retry-after"));
        const wait = Number.isFinite(retryAfter) && retryAfter > 0 ? retryAfter * 1000 : 500 * 2 ** attempt;
        await sleep(Math.min(wait, 15000));
        continue;
      }
      const bodyText = await response.text().catch(() => "");
      const error = new Error(describeHttpError(response.status, bodyText));
      error.status = response.status;
      throw error;
    }
  }

  // Run fn over items with at most `limit` in flight.
  async function mapWithConcurrency(items, limit, fn) {
    const results = new Array(items.length);
    let next = 0;
    const workers = Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, async () => {
      while (next < items.length) {
        const index = next++;
        try {
          results[index] = { ok: true, value: await fn(items[index], index) };
        } catch (error) {
          results[index] = { ok: false, error };
        }
      }
    });
    await Promise.all(workers);
    return results;
  }

  // "https://api.typesafe.ai/x" -> "https://api.typesafe.ai/*"
  function originPattern(url) {
    try {
      const u = new URL(url);
      if (!/^https?:$/.test(u.protocol)) return null;
      return `${u.protocol}//${u.hostname}/*`;
    } catch (_e) {
      return null;
    }
  }

  const api = {
    DEFAULT_API_SETTINGS, buildRequestBody, buildHeaders, buildUrl, getPath,
    parseProbability, describeHttpError, detectText, mapWithConcurrency, originPattern
  };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.JevApi = api;
})(typeof globalThis !== "undefined" ? globalThis : self);
