// Backend wire format. TypeSafe Jev is the default; Cloudflare Workers AI Clef is optional.
// Jev: https://docs.typesafe.ai/api/system-one.md (POST /v1/systemone).
// Clef: POST https://api.cloudflare.com/client/v4/accounts/{account_id}/ai/run/@cf/cloudflare/{model}
// Account ID is placed only in that path. Do not copy it into logs or error text.
// Works as a classic script (importScripts) and as a CommonJS module (tests).

(function (root) {
  const CF_API_ORIGIN = "https://api.cloudflare.com";
  const CF_HOST_PERMISSION = `${CF_API_ORIGIN}/*`;
  const CF_DEFAULT_MODEL = "clef-flash";

  // Saved copies of this sentence are treated as "never customized" and upgraded.
  const LEGACY_DEFAULT_INSTRUCTIONS =
    "Was this short social media reply most likely written or generated by an AI language model rather than by a human?";

  const DEFAULT_API_SETTINGS = Object.freeze({
    // "typesafe" (default) or "cloudflare". Missing/unknown values stay on TypeSafe.
    protocol: "typesafe",
    baseUrl: "https://api.typesafe.ai",
    path: "/v1/systemone",
    authHeader: "Authorization",
    authScheme: "Bearer",
    model: "jev-latest",
    // Used only when protocol is cloudflare. Kept separate so a Jev model name is not overwritten.
    cfModel: CF_DEFAULT_MODEL,
    accountId: "",
    questionKey: "ai_generated",
    // Dot path into the JSON response. "{q}" is replaced with questionKey.
    // Cloudflare ignores this and reads result.answers (falling back to answers).
    responsePath: "answers.{q}.noul",
    instructions: "这条社交媒体回复是不是 AI 生成或 AI 代写的“营业式”评论？",
    criteriaTrue:
      "复述或总结原帖要点、整齐的结构化表达（箭头链路、引号金句、破折号）、泛泛的肯定加一句“要是…就更好了”式建议，没有个人经历、具体问题或情绪",
    criteriaFalse: "带个人经历、具体追问、口语化、错字、情绪或跑题，像真人随手回的"
  });

  function filled(value, fallback) {
    const text = String(value ?? "").trim();
    return text || fallback;
  }

  // Blank or the previous English default → current default. Any other text is kept.
  function resolveInstructions(value) {
    const text = String(value ?? "").trim();
    if (!text || text === LEGACY_DEFAULT_INSTRUCTIONS) return DEFAULT_API_SETTINGS.instructions;
    return text;
  }

  function isCloudflare(cfg) {
    return cfg?.protocol === "cloudflare";
  }

  // Only clef and clef-flash are valid. Anything else, including jev-latest, becomes clef-flash.
  function cloudflareModel(model) {
    const normalized = String(model || "").trim().toLowerCase();
    return normalized === "clef" || normalized === "clef-flash" ? normalized : CF_DEFAULT_MODEL;
  }

  // Whitespace is removed so a pasted id still forms one path segment. The id is not echoed.
  function normalizeAccountId(accountId) {
    return String(accountId || "").replace(/\s+/g, "");
  }

  function modelForRequest(cfg) {
    if (!isCloudflare(cfg)) return cfg.model;
    const preferred = cfg.cfModel != null && String(cfg.cfModel).trim() !== "" ? cfg.cfModel : cfg.model;
    return cloudflareModel(preferred);
  }

  // Request body: ONLY the reply text goes into `state`. No author, ids, timestamps or parent post.
  // Jev and Clef both accept noul criteria as { true, false } strings, so both get the same question.
  function buildRequestBody(text, cfg) {
    return {
      model: modelForRequest(cfg),
      state: String(text),
      questions: {
        [cfg.questionKey]: {
          type: "noul",
          instructions: resolveInstructions(cfg.instructions),
          criteria: {
            true: filled(cfg.criteriaTrue, DEFAULT_API_SETTINGS.criteriaTrue),
            false: filled(cfg.criteriaFalse, DEFAULT_API_SETTINGS.criteriaFalse)
          }
        }
      }
    };
  }

  function buildHeaders(apiKey, cfg) {
    if (isCloudflare(cfg)) {
      return { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` };
    }
    const headers = { "Content-Type": "application/json" };
    if (cfg.authHeader) {
      headers[cfg.authHeader] = cfg.authScheme ? `${cfg.authScheme} ${apiKey}` : apiKey;
    }
    return headers;
  }

  function buildUrl(cfg) {
    const base = String(cfg.baseUrl || "").replace(/\/+$/, "");
    const path = String(cfg.path || "");
    return base + (path.startsWith("/") ? path : `/${path}`);
  }

  // Official Workers AI run URL. model is only clef or clef-flash. No custom base URL.
  function buildCloudflareRunUrl(accountId, model) {
    const id = normalizeAccountId(accountId);
    if (!id) throw new Error("Cloudflare Account ID is required");
    return `${CF_API_ORIGIN}/client/v4/accounts/${encodeURIComponent(id)}/ai/run/@cf/cloudflare/${cloudflareModel(model)}`;
  }

  function requestUrl(cfg) {
    if (isCloudflare(cfg)) return buildCloudflareRunUrl(cfg.accountId, modelForRequest(cfg));
    return buildUrl(cfg);
  }

  function getPath(obj, path) {
    return String(path)
      .split(".")
      .filter(Boolean)
      .reduce((value, key) => (value == null ? undefined : value[key]), obj);
  }

  // Returns an integer percentage 0-100 or throws. Accepts 0-1 probabilities;
  // values in (1, 100] are treated as already-percent for custom endpoints.
  function coerceProbability(value, label) {
    if (typeof value === "string" && value.trim() !== "") value = Number(value);
    if (typeof value !== "number" || !Number.isFinite(value)) {
      throw new Error(`Response has no numeric value at "${label}"`);
    }
    if (value < 0 || value > 100) throw new Error(`Probability out of range: ${value}`);
    const pct = value <= 1 ? value * 100 : value;
    return Math.round(pct);
  }

  function parseProbability(json, cfg) {
    if (isCloudflare(cfg)) {
      // Workers AI wraps the System One payload in result. A bare answers object still parses.
      const answers = json?.result?.answers ?? json?.answers;
      const label = `result.answers.${cfg.questionKey}.noul`;
      return coerceProbability(answers?.[cfg.questionKey]?.noul, label);
    }
    const path = String(cfg.responsePath).split("{q}").join(cfg.questionKey);
    return coerceProbability(getPath(json, path), path);
  }

  function describeHttpError(status, bodyText) {
    const known = {
      400: "Bad request (possibly too long for the model context)",
      401: "Missing or invalid API key",
      413: "Payload too large",
      415: "Unsupported media type",
      422: "Request failed validation",
      429: "Rate limit exceeded",
      529: "TypeSafe is temporarily overloaded"
    };
    const detail = (bodyText || "").slice(0, 200);
    return `HTTP ${status}: ${known[status] || "Request failed"}${detail ? ` - ${detail}` : ""}`;
  }

  // Drop secrets and any /accounts/<id> path segment. Short strings are ignored so a one-character
  // paste cannot blank the rest of the message. Real tokens and account ids are much longer.
  function redactSecrets(text, secrets) {
    let out = String(text ?? "");
    const values = [];
    for (const secret of secrets) {
      const value = String(secret || "").trim();
      if (value.length >= 8) values.push(value);
    }
    values.sort((a, b) => b.length - a.length);
    for (const value of values) {
      out = out.split(value).join("[redacted]");
      const encoded = encodeURIComponent(value);
      if (encoded !== value) out = out.split(encoded).join("[redacted]");
    }
    out = out.replace(/Bearer\s+\S+/gi, "Bearer [redacted]");
    out = out.replace(/\/accounts\/[^/\s"'\\]+/gi, "/accounts/[redacted]");
    return out;
  }

  // Status plus errors[0].message and errors[0].code only. No raw body, token, or account id.
  function cloudflareErrorMessage(status, json, apiKey, cfg) {
    const err = Array.isArray(json?.errors) ? json.errors[0] : null;
    const rawMessage = err && typeof err.message === "string" && err.message.trim() ? err.message.trim() : "Request failed";
    const secrets = [apiKey, cfg?.accountId];
    const message = redactSecrets(rawMessage, secrets).slice(0, 500);
    const hasCode = err && err.code != null && err.code !== "";
    const code = hasCode ? ` (${redactSecrets(String(err.code), secrets)})` : "";
    return `Cloudflare ${status}: ${message}${code}`;
  }

  function isRetryableStatus(status, cloudflare) {
    if (status === 429 || status === 529) return true;
    return Boolean(cloudflare) && status >= 500 && status <= 599;
  }

  async function readJsonBody(response) {
    const text = await response.text().catch(() => "");
    if (!text) return null;
    try {
      return JSON.parse(text);
    } catch (_e) {
      return null;
    }
  }

  // Detect one reply text. Retries 429/529 (and, for Cloudflare, other 5xx) with exponential backoff,
  // honouring Retry-After when a server sends one.
  async function detectText(text, apiKey, cfg, options = {}) {
    const fetchFn = options.fetch || root.fetch.bind(root);
    const sleep = options.sleep || ((ms) => new Promise((r) => setTimeout(r, ms)));
    const maxRetries = options.maxRetries ?? 3;
    const timeoutMs = options.timeoutMs ?? 20000;
    const cloudflare = isCloudflare(cfg);
    const url = requestUrl(cfg);

    for (let attempt = 0; ; attempt++) {
      const controller = typeof AbortController !== "undefined" ? new AbortController() : null;
      const timer = controller ? setTimeout(() => controller.abort(), timeoutMs) : null;
      let response;
      try {
        response = await fetchFn(url, {
          method: "POST",
          headers: buildHeaders(apiKey, cfg),
          body: JSON.stringify(buildRequestBody(text, cfg)),
          signal: controller?.signal
        });
      } catch (error) {
        const message = error?.name === "AbortError" ? "Request timed out" : `Network error: ${error?.message || error}`;
        throw new Error(cloudflare ? redactSecrets(message, [apiKey, cfg?.accountId]) : message);
      } finally {
        if (timer) clearTimeout(timer);
      }

      if (!cloudflare && response.ok) {
        const json = await response.json();
        return { probability: parseProbability(json, cfg), model: json?.model || null };
      }

      if (isRetryableStatus(response.status, cloudflare) && attempt < maxRetries) {
        const retryAfter = Number(response.headers?.get?.("retry-after"));
        const wait = Number.isFinite(retryAfter) && retryAfter > 0 ? retryAfter * 1000 : 500 * 2 ** attempt;
        await sleep(Math.min(wait, 15000));
        continue;
      }

      if (cloudflare) {
        const json = await readJsonBody(response);
        // HTTP 200 with success:false is a failure. A missing success flag is not.
        if (response.ok && json?.success !== false) {
          return {
            probability: parseProbability(json, cfg),
            model: json?.result?.model || json?.model || null
          };
        }
        const error = new Error(cloudflareErrorMessage(response.status, json, apiKey, cfg));
        error.status = response.status;
        throw error;
      }

      const bodyText = await response.text().catch(() => "");
      const error = new Error(describeHttpError(response.status, bodyText));
      error.status = response.status;
      throw error;
    }
  }

  // Run fn over items with at most `limit` in flight.
  async function mapWithConcurrency(items, limit, fn) {
    const results = new Array(items.length);
    let next = 0;
    const workers = Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, async () => {
      while (next < items.length) {
        const index = next++;
        try {
          results[index] = { ok: true, value: await fn(items[index], index) };
        } catch (error) {
          results[index] = { ok: false, error };
        }
      }
    });
    await Promise.all(workers);
    return results;
  }

  // "https://api.typesafe.ai/x" -> "https://api.typesafe.ai/*"
  function originPattern(url) {
    try {
      const u = new URL(url);
      if (!/^https?:$/.test(u.protocol)) return null;
      return `${u.protocol}//${u.hostname}/*`;
    } catch (_e) {
      return null;
    }
  }

  const api = {
    DEFAULT_API_SETTINGS, LEGACY_DEFAULT_INSTRUCTIONS, CF_API_ORIGIN, CF_HOST_PERMISSION, CF_DEFAULT_MODEL,
    resolveInstructions, cloudflareModel, normalizeAccountId, buildCloudflareRunUrl, requestUrl,
    buildRequestBody, buildHeaders, buildUrl, getPath,
    parseProbability, describeHttpError, detectText, mapWithConcurrency, originPattern
  };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.JevApi = api;
})(typeof globalThis !== "undefined" ? globalThis : self);
